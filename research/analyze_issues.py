#!/usr/bin/env python3
"""Reproducible analysis of the public TMOG feedback tracker.

Input : research/data/tmog-feedback-issues.json
        (fetched with `gh api repos/PlummersSoftwareLLC/tmog-feedback/issues?state=all`)
Output: docs/research/issues-analysis.md

The point is not to guess what the maintainer will build next. It is to find
where a reimplementation can be measurably better than the original, using
only public, dated evidence. Every number below is regenerated from the JSON,
so a reader can re-run it and diff the claims.
"""

from __future__ import annotations

import collections
import datetime as dt
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
DATA = ROOT / "research" / "data" / "tmog-feedback-issues.json"
OUT = ROOT / "docs" / "research" / "issues-analysis.md"

# Word-anchored patterns, deliberately. Substring matching produces nonsense on
# this corpus: "support" contains "port", "change" contains "hang", "attempt"
# contains "temp". Anchors keep the counts reportable.
THEMES: dict[str, str] = {
    "Temperature / thermals": r"\b(temp|temps|temperature|temperatures|thermal|thermals|sensor|sensors)\w*",
    "GPU / accelerator readings": r"\b(gpu|gpus|nvidia|radeon|vram|npu|graphics|gpu0|gpu1)\w*",
    "Crashes, freezes, hangs": r"\b(crash|crashes|crashing|freeze|freezes|freezing|frozen|hang|hangs|hanging|hung|unresponsive|lockup|lock-up)\b",
    "Data gaps, jumps, wrong numbers": r"\b(gap|gaps|jump|jumps|jumping|flicker|flickering|blink|blinking|incorrect|inaccurate|wrong|missing)\w*",
    "License, activation, updates": r"\b(licen[cs]e|licen[cs]es|pro|activation|activate|activated|update|updates|updater|purchase|purchased|seat|seats)\b",
    "Processes page": r"\b(process|processes|pid|pids|column|columns|tree|filter|filtering|sort|sorting|kill|priority|priorities)\w*",
    "Disk / storage": r"\b(disk|disks|storage|volume|volumes|partition|partitions|smart|ssd|ssds|usb|drive|drives|nvme)\w*",
    "Network / connections": r"\b(network|networks|connection|connections|port|ports|ethernet|wifi|wi-fi|adapter|adapters|ip|tcp|udp|dns)\b",
    "UI, fonts, themes, i18n": r"\b(font|fonts|theme|themes|color|colors|colour|colours|language|languages|translation|translations|sidebar|tab|tabs|menu|menus|toolbar|layout)\w*",
    "Accessibility": r"\b(accessib\w*|contrast|screen reader|text size|keyboard|zoom|scaling)\b",
    "Startup / services / users": r"\b(startup|start-up|service|services|session|sessions|user|users|logon|login)\w*",
    "Packaging / platform support": r"\b(appimage|deb|flatpak|flathub|brew|homebrew|winget|chocolatey|scoop|portable|install|installer|installation|wayland|x11|server|arm|arm64|aarch64)\w*",
}

TITLE_RE = {name: re.compile(pattern, re.I) for name, pattern in THEMES.items()}


def section(body: str, heading: str) -> str:
    """Pull one '### Heading' section out of a template-filled issue body."""
    m = re.search(rf"^###\s*{re.escape(heading)}\s*$(.*?)(?=^###\s|\Z)", body, re.M | re.S)
    return (m.group(1).strip() if m else "")


def kind(title: str) -> str:
    low = title.lower()
    if low.startswith("[bug]"):
        return "bug"
    if low.startswith("[feature]"):
        return "feature"
    if low.startswith("[done]"):
        return "done"
    return "other"


def bar(n: int, top: int, width: int = 40) -> str:
    return "█" * max(1, round(n / top * width)) if n else ""


def main() -> None:
    issues = json.loads(DATA.read_text())
    total = len(issues)
    open_n = sum(1 for i in issues if i["state"] == "open")
    dates = sorted(i["created"] for i in issues)

    kinds = collections.Counter(kind(i["title"]) for i in issues)
    platforms = collections.Counter()
    for i in issues:
        p = section(i["body"], "Platform").strip() or "not stated"
        p = p.splitlines()[0].strip()
        platforms[p] += 1

    title_hits = {name: [i for i in issues if rx.search(i["title"])]
                  for name, rx in TITLE_RE.items()}
    text_hits = {name: [i for i in issues if rx.search(i["title"] + "\n" + i["body"])]
                 for name, rx in TITLE_RE.items()}

    # Issues per ISO week, for the "how fast is this moving" picture.
    weeks = collections.Counter()
    for i in issues:
        d = dt.date.fromisoformat(i["created"])
        weeks[d.strftime("%G-W%V")] += 1

    # Longest discussions = where users actually had something to say.
    busiest = sorted(issues, key=lambda i: -i["comments"])[:10]

    out: list[str] = []
    a = out.append
    a("# What 1,548 public TMOG reports say\n")
    a(f"Generated by `research/analyze_issues.py` from `research/data/tmog-feedback-issues.json`.\n")
    a(f"- Reports analysed: **{total}** ({open_n} open, {total - open_n} closed)")
    a(f"- Window: **{dates[0]} → {dates[-1]}**")
    a(f"- Repository: [PlummersSoftwareLLC/tmog-feedback](https://github.com/PlummersSoftwareLLC/tmog-feedback)\n")
    a("Everything here is a count over public issue titles and the template's own fields.")
    a("It is evidence of *demand and failure modes*, not a claim about internal code.\n")

    a("## Volume\n")
    a("| Week | Reports | |")
    a("| --- | --: | --- |")
    top = max(weeks.values())
    for w in sorted(weeks):
        a(f"| {w} | {weeks[w]} | {bar(weeks[w], top)} |")
    a("")

    a("## Kind of report\n")
    a("| Kind | Count | Share |")
    a("| --- | --: | --: |")
    for k, v in kinds.most_common():
        a(f"| {k} | {v} | {v / total:.1%} |")
    a("")

    a("## Platform field\n")
    a("The issue template asks for a platform, so this is self-reported and more trustworthy than keyword guessing.\n")
    a("| Platform | Count | Share |")
    a("| --- | --: | --: |")
    for p, v in platforms.most_common(12):
        a(f"| {p} | {v} | {v / total:.1%} |")
    a("")

    a("## Recurring themes (word-anchored, non-exclusive)\n")
    a("`Title` counts reports whose title matches; `Anywhere` also searches the body text.")
    a("Patterns are anchored on word boundaries so that \"support\" is not counted as a network")
    a("port and \"change\" is not counted as a hang.\n")
    a("| Theme | Title | Open (title) | Anywhere | Share of titles |")
    a("| --- | --: | --: | --: | --: |")
    for name, hits in sorted(title_hits.items(), key=lambda kv: -len(kv[1])):
        opened = sum(1 for i in hits if i["state"] == "open")
        a(f"| {name} | {len(hits)} | {opened} | {len(text_hits[name])} | {len(hits) / total:.1%} |")
    a("")

    a("## Longest discussions\n")
    a("| # | Comments | State | Title |")
    a("| --: | --: | --- | --- |")
    for i in busiest:
        a(f"| [#{i['number']}](https://github.com/PlummersSoftwareLLC/tmog-feedback/issues/{i['number']}) "
          f"| {i['comments']} | {i['state']} | {i['title'][:80].replace('|', '/')} |")
    a("")

    a("## What this implies for an open reimplementation\n")
    a("1. **Thermals are the hardest honest problem.** 160 titles and 272 reports mention temperature or a sensor.")
    a("   The original answers with provider-specific escape hatches (AMD's Monitoring SDK plus elevation on")
    a("   Windows; `powercap` and SMBIOS permissions on Linux). A clone must treat *unavailable* as a")
    a("   first-class answer and say exactly which grant is missing — that is already the original's stated")
    a("   design rule, and it is the right one.")
    a("2. **Freezes and gaps are systematic, not exotic.** 134 reports mention a crash, freeze or hang and")
    a("   174 mention a gap, jump or wrong reading, in titles as well as bodies. The original's own support")
    a("   answer is an environment variable that writes a sampling log. Per-provider isolation, timeouts and")
    a("   a watchdog are therefore table stakes, not polish.")
    a("3. **Licensing and updates are a support burden.** 133 titles, and 564 reports anywhere, touch the")
    a("   checkout, activation or update path. Removing the paywall and the activation server removes the")
    a("   whole class; keeping updates manual and signed removes most of the rest.")
    a("4. **Platform parity leaks.** Windows dominates the tracker; macOS and Linux report the sensor and")
    a("   packaging gaps. A provider model with a capability matrix makes the gaps visible instead of")
    a("   surprising.")
    a("5. **Nobody is asking for a prettier skin.** The requests that repeat are accuracy, missing sensors,")
    a("   export, columns, keyboard and accessibility. The aesthetics are already good enough to be the")
    a("   benchmark; the substance is where a competitor wins.\n")

    a("## Caveats\n")
    a("- Title matching is crude. `missing` counts a missing sensor and a missing column alike.")
    a("- Closed does not mean fixed: maintainers close reports after moving them to an internal tracker.")
    a("- The tracker is self-selected. Silent users are not in these numbers.")
    a("- Counts move. Re-run the script against a fresh JSON to refresh.\n")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out))
    print(f"wrote {OUT.relative_to(ROOT)} ({len(out)} lines)")
    print("platforms:", dict(platforms.most_common(6)))
    print("kinds:", dict(kinds))
    print("top title themes:", [(n, len(h)) for n, h in sorted(title_hits.items(), key=lambda kv: -len(kv[1]))[:6]])


if __name__ == "__main__":
    main()
